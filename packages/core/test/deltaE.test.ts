describe('CIEDE2000', () => {
  it(`Sharma 标准 ${SHARMA.length} 组数据，误差 < 1e-4`, () => {
    const failures: string[] = [];
    SHARMA.forEach(([p1, p2, expected], i) => {
      const got = deltaE2000Raw(p1[0], p1[1], p1[2], p2[0], p2[1], p2[2]);
      if (Math.abs(got - expected) > 1e-4) {
        failures.push(`#${i + 1}: 期望 ${expected}, 实际 ${got.toFixed(6)}`);
      }
    });
    expect(failures).toEqual([]);
  });

  it('对称性：dE(a,b) === dE(b,a)', () => {
    expect(
      Math.abs(
        deltaE2000Raw(50, 2.5, 0, 73, 25, -18) - deltaE2000Raw(73, 25, -18, 50, 2.5, 0),
      ),
    ).toBeLessThan(1e-12);
  });

  it('自身比对为 0', () => {
    expect(deltaE2000Raw(50, 20, -30, 50, 20, -30)).toBeLessThan(1e-12);
  });

  it('产品分级文案', () => {
    expect(describeDelta(0.5)).toBe('几乎无法分辨');
    expect(describeDelta(3)).toBe('明显能看出不同');
    expect(describeDelta(50)).toBe('完全不同');
  });
});

describe('色彩空间转换', () => {
  const CASES: Array<[string, number, number, number]> = [
    ['#FFFFFF', 100.0, 0.0, 0.0],
    ['#000000', 0.0, 0.0, 0.0],
    ['#FF0000', 53.2408, 80.0925, 67.2032],
    ['#00FF00', 87.7347, -86.1827, 83.1793],
    ['#0000FF', 32.297, 79.1875, -107.8602],
    ['#808080', 53.585, 0.0, 0.0],
  ];

  it('已知 sRGB → Lab 对照表', () => {
    for (const [hex, L, a, b] of CASES) {
      const lab = hexToLab(hex);
      expect(Math.abs(lab.L - L), `${hex} L`).toBeLessThan(0.02);
      expect(Math.abs(lab.a - a), `${hex} a`).toBeLessThan(0.02);
      expect(Math.abs(lab.b - b), `${hex} b`).toBeLessThan(0.02);
    }
  });

  it('Lab → RGB 往返误差 ≤ 1', () => {
    for (const [hex] of CASES) {
      const lab = hexToLab(hex);
      const back = labToRgb(lab.L, lab.a, lab.b);
      const orig = { r: 0, g: 0, b: 0 };
      const n = parseInt(hex.slice(1), 16);
      orig.r = (n >> 16) & 255;
      orig.g = (n >> 8) & 255;
      orig.b = n & 255;
      expect(Math.abs(back.r - orig.r)).toBeLessThanOrEqual(1);
      expect(Math.abs(back.g - orig.g)).toBeLessThanOrEqual(1);
      expect(Math.abs(back.b - orig.b)).toBeLessThanOrEqual(1);
    }
  });

  it('hex 解析容错', () => {
    expect(rgbToHex(255, 255, 255)).toBe('#FFFFFF');
    expect(rgbToHex(0, 0, 0)).toBe('#000000');
  });
});
